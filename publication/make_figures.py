#!/usr/bin/env python3
"""Figures and summary tables for the GPU compaction results.

Reads the raw results archived in publication/data/:
  compaction/v<value>-<codec>-s3.jsonl  lsm_compaction_bench: native_cpu, gpu_output, cuda_merge (Stage 3)
  compaction/v<value>-<codec>-s2.jsonl  lsm_compaction_bench: cuda_merge with LSM_DISABLE_GPU_BUILD=1 (Stage 2)
  database/batched-ingest.jsonl         system_campaign.py + lsm_system_bench
Isolated compaction numbers are medians of repetitions 1-3 (repetition 0 is a
cold start). Every plotted run must match native RocksDB exactly.
Run: python3 publication/make_figures.py
"""

import json
import statistics
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
OUT = HERE / "figures"

GREY = "#9aa0a6"
LIGHT = "#a8c8e8"
MID = "#4a90c8"
ACCENT = "#d9822b"
INK = "#202124"

plt.rcParams.update({
    "font.family": "DejaVu Sans",
    "font.size": 10,
    "axes.edgecolor": "#5f6368",
    "axes.labelcolor": INK,
    "axes.titlesize": 12,
    "axes.titleweight": "bold",
    "axes.spines.top": False,
    "axes.spines.right": False,
    "xtick.color": INK,
    "ytick.color": INK,
    "legend.frameon": False,
    "savefig.bbox": "tight",
    "savefig.dpi": 200,
})

NATIVE, OUTPUT_ONLY, MERGE, FULL = ("Native RocksDB", "GPU compression only", "GPU merge",
                                    "GPU merge + block building")
COLORS = {NATIVE: GREY, OUTPUT_ONLY: LIGHT, MERGE: MID, FULL: ACCENT}
WORKLOADS = [("v32-lz4", "32 B values"), ("v128-lz4", "128 B values"), ("v1024-lz4", "1 KB values"),
             ("v128-none", "128 B values,\nno compression")]


def load_compaction():
    """{tag: {design: {"wall": s, "cpu": s, "cpu_per_gib": s}}} from the medians of repetitions 1-3."""
    result = {}
    for tag, _ in WORKLOADS:
        runs = {}
        for stage in ("s3", "s2"):
            for line in (DATA / "compaction" / f"{tag}-{stage}.jsonl").read_text().splitlines():
                run = json.loads(line)
                if not run["matches_reference"]:
                    raise SystemExit(f"{tag}: {run['mode']} repetition {run['repetition']} differs from native")
                if run["repetition"] == 0:
                    continue
                design = {"native_cpu": NATIVE, "gpu_output": OUTPUT_ONLY}.get(run["mode"], FULL if stage == "s3" else MERGE)
                runs.setdefault(design, []).append(run)
        result[tag] = {design: {"wall": statistics.median(r["wall_seconds"] for r in rs),
                                "cpu": statistics.median(r["process_cpu_seconds"] for r in rs),
                                "cpu_per_gib": statistics.median(r["process_cpu_seconds"] / (r["input_bytes"] / 2**30) for r in rs),
                                "runs": len(rs)}
                       for design, rs in runs.items()}
    return result


def load_database():
    """Batched runs: each design at the background-job setting with the best end-to-end throughput."""
    design_of = {"native_cpu": NATIVE, "gpu_output": OUTPUT_ONLY, "cuda_merge": FULL}
    batched, single = {}, {}
    for line in (DATA / "database" / "batched-ingest.jsonl").read_text().splitlines():
        record = json.loads(line)
        result = record["result"]
        if record["exit_code"] != 0 or result.get("verification", {}).get("keys") != result["config"]["records"]:
            raise SystemExit(f"database run {record['index']} failed or was not verified")
        end = result["ingest_and_compact"]
        row = {"window": result["throughput"]["ops_per_second"], "end_to_end": end["ops_per_second"],
               "p99_ms": result["write_latency"]["p99_ns"] / 1e6, "cpu_us": end["cpu_microseconds_per_op"],
               "stall": result["stall_fraction"] * 100, "drain": end["drain_seconds"],
               "background_jobs": record["flags"]["background-jobs"]}
        target = batched if record["flags"].get("batch-size", 1) > 1 else single
        design = design_of[record["trial"]["mode"]]
        if design not in target or row["end_to_end"] > target[design]["end_to_end"]:
            target[design] = row
    return batched, single


COMPACTION = load_compaction()
BATCHED, SINGLE = load_database()
CPU_PER_GIB = {d: [COMPACTION[t][d]["cpu_per_gib"] for t, _ in WORKLOADS] for d in (NATIVE, OUTPUT_ONLY, MERGE, FULL)}
SPEEDUP = {d: [COMPACTION[t][NATIVE]["wall"] / COMPACTION[t][d]["wall"] for t, _ in WORKLOADS]
           for d in (OUTPUT_ONLY, MERGE, FULL)}
WORKLOAD_LABELS = [label for _, label in WORKLOADS]


def write_summary():
    lines = ["# Numbers behind the figures", "", "Generated by `make_figures.py` from `data/`.", "",
             "## Isolated compaction (median of 3 warm repetitions)", "",
             "| Workload | Design | Wall s | Speed-up | CPU s | CPU less | CPU s/GiB |", "|---|---|---|---|---|---|---|"]
    for tag, label in WORKLOADS:
        base = COMPACTION[tag][NATIVE]
        for design in (NATIVE, OUTPUT_ONLY, MERGE, FULL):
            row = COMPACTION[tag][design]
            lines.append(f"| {label.replace(chr(10), ' ')} | {design} | {row['wall']:.2f} | {base['wall'] / row['wall']:.2f}x | "
                         f"{row['cpu']:.2f} | {base['cpu'] / row['cpu']:.2f}x | {row['cpu_per_gib']:.2f} |")
    for title, data in (("Whole database, batched writes (best background-job setting per design)", BATCHED),
                        ("Whole database, single writes", SINGLE)):
        lines += ["", f"## {title}", "",
                  "| Design | Bg jobs | Ops/s during run | Ops/s incl. catch-up | Catch-up s | CPU us/op | p99 write ms | Stalled % |",
                  "|---|---|---|---|---|---|---|---|"]
        for design, row in data.items():
            lines.append(f"| {design} | {row['background_jobs']} | {row['window']:,.0f} | {row['end_to_end']:,.0f} | "
                         f"{row['drain']:.1f} | {row['cpu_us']:.2f} | {row['p99_ms']:.3f} | {row['stall']:.0f} |")
    (HERE / "data" / "summary.md").write_text("\n".join(lines) + "\n")


def label_bars(ax, bars, fmt, pad=3, size=8.5):
    for bar in bars:
        height = bar.get_height()
        ax.annotate(fmt(height), (bar.get_x() + bar.get_width() / 2, height), xytext=(0, pad),
                    textcoords="offset points", ha="center", va="bottom", fontsize=size, color=INK)


def save(fig, name):
    OUT.mkdir(exist_ok=True)
    fig.savefig(OUT / f"{name}.png")
    fig.savefig(OUT / f"{name}.pdf")
    plt.close(fig)


def figure_compaction_cpu():
    fig, ax = plt.subplots(figsize=(8.6, 4.2))
    width = 0.2
    for offset, (name, values) in enumerate(CPU_PER_GIB.items()):
        xs = [index + (offset - 1.5) * width for index in range(len(WORKLOADS))]
        bars = ax.bar(xs, values, width, label=name, color=COLORS[name])
        label_bars(ax, bars, lambda v: f"{v:.1f}", size=8)
    ax.set_xticks(range(len(WORKLOADS)), WORKLOAD_LABELS)
    ax.set_ylabel("CPU seconds per GiB compacted")
    ax.set_title("CPU cost of compaction")
    ax.set_ylim(0, max(max(v) for v in CPU_PER_GIB.values()) * 1.15)
    ax.legend(ncol=2, loc="upper right")
    ax.yaxis.grid(True, color="#e8eaed")
    ax.set_axisbelow(True)
    save(fig, "1_compaction_cpu")


def figure_compaction_speedup():
    fig, ax = plt.subplots(figsize=(8.6, 4.2))
    width = 0.26
    for offset, (name, values) in enumerate(SPEEDUP.items()):
        xs = [index + (offset - 1) * width for index in range(len(WORKLOADS))]
        bars = ax.bar(xs, values, width, label=name, color=COLORS[name])
        label_bars(ax, bars, lambda v: f"{v:.1f}×", size=8.5)
    ax.axhline(1.0, color=GREY, linestyle="--", linewidth=1, label="Native RocksDB (1×)")
    ax.set_xticks(range(len(WORKLOADS)), WORKLOAD_LABELS)
    ax.set_ylabel("Speed-up over native RocksDB")
    ax.set_title("Compaction speed")
    ax.set_ylim(0, max(max(v) for v in SPEEDUP.values()) * 1.15)
    ax.legend(loc="upper right")
    ax.yaxis.grid(True, color="#e8eaed")
    ax.set_axisbelow(True)
    save(fig, "2_compaction_speedup")


def figure_database():
    names = [d for d in (NATIVE, OUTPUT_ONLY, FULL) if d in BATCHED]
    colors = [COLORS[name] for name in names]
    short = ["Native\nRocksDB", "GPU compression\nonly", "GPU merge +\nblock building"]
    fig, axes = plt.subplots(1, 3, figsize=(11.5, 3.9))
    panels = [
        ("Throughput (thousand ops/s)", [BATCHED[n]["end_to_end"] / 1000 for n in names], lambda v: f"{v:.0f}k"),
        ("p99 write latency (ms)", [BATCHED[n]["p99_ms"] for n in names], lambda v: f"{v:.1f}"),
        ("CPU per operation (µs)", [BATCHED[n]["cpu_us"] for n in names], lambda v: f"{v:.1f}"),
    ]
    for ax, (title, values, fmt) in zip(axes, panels):
        bars = ax.bar(range(len(names)), values, 0.62, color=colors)
        label_bars(ax, bars, fmt)
        ax.set_xticks(range(len(names)), short, fontsize=8.5)
        ax.set_title(title, fontsize=10.5)
        ax.set_ylim(0, max(values) * 1.18)
        ax.yaxis.grid(True, color="#e8eaed")
        ax.set_axisbelow(True)
    fig.suptitle("Whole database: batched writes on 4 CPU cores", fontweight="bold", fontsize=12, y=1.03)
    fig.text(0.5, -0.09, "Throughput counts the time to finish all compaction the writes caused. "
             "50 M keys, 128-byte values, 100 writes per batch.\nBackground jobs: " +
             ", ".join(f"{name} {BATCHED[name]['background_jobs']}" for name in names) + ". Single runs.",
             ha="center", fontsize=8.5, color="#5f6368")
    fig.tight_layout()
    save(fig, "3_database_batched")


def figure_deferred_compaction():
    groups = [("Batched writes", BATCHED), ("Single writes", SINGLE)]
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.0), sharey=False)
    for ax, (title, data) in zip(axes, groups):
        names = [n for n in (NATIVE, FULL) if n in data]
        width = 0.36
        for index, name in enumerate(names):
            window = data[name]["window"] / 1000
            total = data[name]["end_to_end"] / 1000
            bars = ax.bar([index - width / 2], [window], width, color=COLORS[name], alpha=0.35,
                          label="During the run only" if index == 0 else None)
            label_bars(ax, bars, lambda v: f"{v:.0f}k", size=8.5)
            bars = ax.bar([index + width / 2], [total], width, color=COLORS[name],
                          label="Including catch-up compaction" if index == 0 else None)
            label_bars(ax, bars, lambda v: f"{v:.0f}k", size=8.5)
        ax.set_xticks(range(len(names)), [f"{label}\n(catch-up {data[name]['drain']:.0f} s)" for label, name in
                                          zip(["Native RocksDB", "GPU merge + block building"], names)])
        ax.set_title(title, fontsize=11)
        ax.set_ylabel("Thousand ops/s")
        ax.set_ylim(0, max(d["window"] for d in data.values()) / 1000 * 1.2)
        ax.yaxis.grid(True, color="#e8eaed")
        ax.set_axisbelow(True)
    axes[0].legend(loc="upper left", fontsize=8.5)
    fig.suptitle("Short runs overstate native RocksDB: it postpones compaction", fontweight="bold", fontsize=12, y=1.02)
    fig.tight_layout()
    save(fig, "4_deferred_compaction")


if __name__ == "__main__":
    write_summary()
    figure_compaction_cpu()
    figure_compaction_speedup()
    figure_database()
    figure_deferred_compaction()
    print("wrote", sorted(p.name for p in OUT.glob("*.png")))
